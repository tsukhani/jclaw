#!/usr/bin/env node
// Writes conf/retired-release-files.tsv: every file content a release up to v1.0.23 shipped at a path the
// current tree no longer ships. Those releases recorded no list of their files, so an install upgraded from one
// carries them all forward; jclaw.sh's first start of a newer release removes each copy that still matches
// (JF-522). Contract and exit codes: bin/README.md.

import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const PROJECT_ROOT = resolve(fileURLToPath(import.meta.url), "..", "..");
export const TABLE = join("conf", "retired-release-files.tsv");

// The last release whose bundle carries no release-files.tsv. Later ones list their own files, which the upgrade
// reads instead, so this table never grows past it.
export const LAST_UNLISTED = "v1.0.23";

// jclaw.sh's UPGRADE_NO_MERGE plus the bundle's own lib/, modules/ and framework/: an upgrade replaces these
// wholesale and never carries a file out of them, so none of them can be left behind.
const NEVER_CARRIED = ["precompiled", "lib", "framework", "modules", ".classpath", "public/spa", "server.pid"];

// The operator's: early releases seeded workspace/main/AGENT.md and SOUL.md, and an unedited one is still the
// main agent's persona; a skill's credentials/ folder is where its secrets go, whatever a release once put there.
// jclaw.sh skips the same paths. An install holding app/ is a source checkout, which neither upgrades nor runs
// the cleanup.
export const NEVER_REMOVED = ["workspace", "workspace-test", "data", "logs", "certs", "tmp", "app"];
const SKILL_CREDENTIALS = /^skills\/[^/]+\/credentials\//;

const USAGE = `Usage: node bin/retired-release-files.mjs [--check]

  (none)    write ${TABLE} from the v* tags up to ${LAST_UNLISTED} and the files the index ships
  --check   write nothing; exit 1 when ${TABLE} differs from what it would write

Exit: 0 written or current, 1 --check found it stale, 2 git failed or no tag was found.`;

export function parseVersion(tag) {
  const m = /^v(\d+)\.(\d+)\.(\d+)$/.exec(tag);
  return m ? m.slice(1).map(Number) : null;
}

export function versionAtMost(tag, limit) {
  const a = parseVersion(tag);
  const b = parseVersion(limit);
  if (!a || !b) return false;
  for (let i = 0; i < 3; i++) if (a[i] !== b[i]) return a[i] < b[i];
  return true;
}

export function distignorePrefixes(text) {
  return text.split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("#"));
}

// The packager's filter (Play1Plugin's startsWith on each .distignore line), applied to one git path.
const under = (path, roots) => roots.some((n) => path === n || path.startsWith(`${n}/`));

export function ships(path, prefixes) {
  if (under(path, NEVER_CARRIED)) return false;
  return !prefixes.some((p) => path.startsWith(p));
}

export const retirable = (path) => !under(path, NEVER_REMOVED) && !SKILL_CREDENTIALS.test(path);

function git(args, input) {
  const r = spawnSync("git", args, { cwd: PROJECT_ROOT, input, maxBuffer: 1 << 30 });
  if (r.status !== 0) throw new Error(`git ${args.join(" ")}: ${r.stderr.toString().trim()}`);
  return r.stdout;
}

// Regular files only: a symlink or a submodule entry is no file content an install could hold a copy of.
function treeBlobs(ref) {
  const out = new Map();
  for (const entry of git(["ls-tree", "-r", "-z", "--full-tree", ref]).toString().split("\0")) {
    const m = /^(100644|100755) blob ([0-9a-f]+)\t(.+)$/s.exec(entry);
    if (m) out.set(m[3], m[2]);
  }
  return out;
}

function indexPaths() {
  return git(["ls-files", "-z"]).toString().split("\0").filter(Boolean);
}

function blobSha256s(blobIds) {
  const out = new Map();
  if (blobIds.length === 0) return out;
  const buf = git(["cat-file", "--batch"], `${blobIds.join("\n")}\n`);
  let at = 0;
  for (const id of blobIds) {
    const nl = buf.indexOf(0x0a, at);
    const [, , size] = buf.subarray(at, nl).toString().split(" ");
    const start = nl + 1;
    const end = start + Number(size);
    out.set(id, createHash("sha256").update(buf.subarray(start, end)).digest("hex"));
    at = end + 1;
  }
  return out;
}

export function render(rows) {
  const lines = [...rows].sort((a, b) => (a[0] === b[0] ? a[1].localeCompare(b[1]) : a[0] < b[0] ? -1 : 1))
    .map(([path, sha]) => `${path}\t${sha}`);
  return `# Generated by bin/retired-release-files.mjs; do not edit by hand.\n`
    + `# Every file content a release up to ${LAST_UNLISTED} shipped, at a path this release does not ship:\n`
    + `# path<TAB>sha256. jclaw.sh removes a copy that matches, once, after an upgrade from such a release.\n`
    + lines.join("\n") + (lines.length ? "\n" : "");
}

export function generate() {
  const tags = git(["tag", "-l", "v*"]).toString().split("\n").filter((t) => versionAtMost(t, LAST_UNLISTED));
  if (tags.length === 0) throw new Error(`no v* tag up to ${LAST_UNLISTED}; fetch the tags first`);
  const shippedNow = new Set(indexPaths().filter((p) => ships(p, distignorePrefixes(
    existsSync(join(PROJECT_ROOT, ".distignore")) ? readFileSync(join(PROJECT_ROOT, ".distignore"), "utf8") : ""))));

  const blobsByPath = new Map();
  for (const tag of tags) {
    let prefixes = [];
    try {
      prefixes = distignorePrefixes(git(["cat-file", "-p", `${tag}:.distignore`]).toString());
    } catch {
      // An early tag with no .distignore shipped every tracked file.
    }
    for (const [path, blob] of treeBlobs(tag)) {
      if (shippedNow.has(path) || !ships(path, prefixes) || !retirable(path)) continue;
      if (!blobsByPath.has(path)) blobsByPath.set(path, new Set());
      blobsByPath.get(path).add(blob);
    }
  }
  const allBlobs = [...new Set([...blobsByPath.values()].flatMap((s) => [...s]))];
  const sha = blobSha256s(allBlobs);
  const rows = [];
  for (const [path, blobs] of blobsByPath) for (const b of blobs) rows.push([path, sha.get(b)]);
  return { text: render(rows), tags: tags.length, paths: blobsByPath.size, rows: rows.length };
}

function main(argv) {
  if (argv.includes("--help") || argv.some((a) => a !== "--check")) {
    console.log(USAGE);
    return argv.includes("--help") ? 0 : 2;
  }
  let result;
  try {
    result = generate();
  } catch (e) {
    console.error(`retired-release-files: ${e.message}`);
    return 2;
  }
  const target = join(PROJECT_ROOT, TABLE);
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (argv.includes("--check")) {
    if (current === result.text) return 0;
    console.error(`${TABLE} is stale: run node bin/retired-release-files.mjs`);
    return 1;
  }
  writeFileSync(target, result.text);
  console.log(`${TABLE}: ${result.rows} contents at ${result.paths} paths, from ${result.tags} tags`);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exit(main(process.argv.slice(2)));
