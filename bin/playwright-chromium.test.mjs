// node --test bin/playwright-chromium.test.mjs
// Every case builds its own Gradle cache, driver jar and browsers directory, so none reads the real ones.

import { deepStrictEqual, strictEqual } from "node:assert";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

import {
  browsersPath, cachedRevisions, check, lockedDriverVersion, missingFolders, pinnedRevisions,
} from "./playwright-chromium.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const LOCK = [
  "com.microsoft.playwright:driver-bundle:1.64.0=compileClasspath,runtimeClasspath",
  "com.microsoft.playwright:driver:1.64.0=compileClasspath,runtimeClasspath",
  "com.microsoft.playwright:playwright:1.64.0=compileClasspath,runtimeClasspath",
].join("\n");
const BROWSERS = (over = {}) => JSON.stringify({ comment: "Do not edit this file", browsers: [
  { name: "chromium", revision: "1248", installByDefault: true },
  { name: "chromium-headless-shell", revision: "1248", installByDefault: true },
  { name: "firefox", revision: "1555", installByDefault: true },
  { name: "ffmpeg", revision: "1013", installByDefault: true },
].map((b) => ({ ...b, ...over[b.name] })).filter((b) => b.revision !== undefined) });
const PINNED = { chromium: "1248", "chromium-headless-shell": "1248", ffmpeg: "1013" };

function scratch() {
  const dir = mkdtempSync(join(tmpdir(), "pw-chromium-"));
  return { dir, done: () => rmSync(dir, { recursive: true, force: true }) };
}

/** A browsers directory holding these folders, each with INSTALLATION_COMPLETE unless listed in bare. */
function cache(dir, folders, bare = []) {
  const root = join(dir, "ms-playwright");
  mkdirSync(root, { recursive: true });
  for (const f of folders) {
    mkdirSync(join(root, f));
    if (!bare.includes(f)) writeFileSync(join(root, f, "INSTALLATION_COMPLETE"), "");
  }
  return root;
}

/** A Gradle home whose cache holds driver-<version>.jar with this browsers.json. */
function gradleHome(dir, version, browsersJson) {
  const src = join(dir, "jar-src");
  mkdirSync(join(src, "driver", "package"), { recursive: true });
  writeFileSync(join(src, "driver", "package", "browsers.json"), browsersJson);
  const home = join(dir, "gradle");
  const hash = join(home, "caches", "modules-2", "files-2.1", "com.microsoft.playwright", "driver", version, "9777924d");
  mkdirSync(hash, { recursive: true });
  const zip = spawnSync("zip", ["-q", "-r", join(hash, `driver-${version}.jar`), "driver"], { cwd: src });
  strictEqual(zip.status, 0, `zip failed: ${zip.stderr}`);
  return home;
}

function repo(dir, lockfile = LOCK) {
  const root = join(dir, "repo");
  mkdirSync(root);
  if (lockfile !== null) writeFileSync(join(root, "gradle.lockfile"), lockfile);
  return root;
}

const COMPLETE = ["chromium-1248", "chromium_headless_shell-1248", "ffmpeg-1013"];

test("the driver version is gradle.lockfile's driver line, never driver-bundle's", () => {
  strictEqual(lockedDriverVersion(LOCK), "1.64.0");
  strictEqual(lockedDriverVersion("com.microsoft.playwright:driver-bundle:1.64.0=runtimeClasspath"), null);
  strictEqual(lockedDriverVersion(""), null);
  strictEqual(lockedDriverVersion(null), null);
});

test("the pinned revisions are read by browser name", () => {
  deepStrictEqual(pinnedRevisions(BROWSERS()),
    { chromium: "1248", "chromium-headless-shell": "1248", firefox: "1555", ffmpeg: "1013" });
  deepStrictEqual(pinnedRevisions("{}"), {});
});

test("the browsers directory is PLAYWRIGHT_BROWSERS_PATH, else the macOS or Linux cache", () => {
  strictEqual(browsersPath({ PLAYWRIGHT_BROWSERS_PATH: "/srv/pw" }, "darwin", "/Users/me"), "/srv/pw");
  strictEqual(browsersPath({ PLAYWRIGHT_BROWSERS_PATH: "0" }, "darwin", "/Users/me"), null);
  strictEqual(browsersPath({ PLAYWRIGHT_BROWSERS_PATH: " " }, "darwin", "/Users/me"),
    "/Users/me/Library/Caches/ms-playwright");
  strictEqual(browsersPath({}, "linux", "/home/me"), "/home/me/.cache/ms-playwright");
  strictEqual(browsersPath({ XDG_CACHE_HOME: "/var/cache" }, "linux", "/home/me"), "/var/cache/ms-playwright");
  strictEqual(browsersPath({ XDG_CACHE_HOME: "" }, "linux", "/home/me"), "/home/me/.cache/ms-playwright");
});

test("the pinned build is installed only with a marker in each of its three folders", () => {
  const s = scratch();
  try {
    deepStrictEqual(missingFolders(cache(join(s.dir, "all"), COMPLETE), PINNED), []);
    deepStrictEqual(missingFolders(cache(join(s.dir, "other"),
      ["chromium-1254", "chromium_headless_shell-1234", "chromium_headless_shell-1254", "ffmpeg-1011"]), PINNED),
    COMPLETE);
    deepStrictEqual(missingFolders(cache(join(s.dir, "cut"), COMPLETE, ["ffmpeg-1013"]), PINNED), ["ffmpeg-1013"]);
    deepStrictEqual(missingFolders(join(s.dir, "absent"), PINNED), COMPLETE);
  } finally {
    s.done();
  }
});

test("the cache's complete headless-shell revisions are listed in numeric order", () => {
  const s = scratch();
  try {
    const root = cache(s.dir, ["chromium_headless_shell-1254", "chromium_headless_shell-999", "chromium-1300",
      "chromium_headless_shell-1234", "chromium_headless_shell-1260", "ffmpeg-1011", "mcp-chrome-36ed067"],
    ["chromium_headless_shell-1260"]);
    deepStrictEqual(cachedRevisions(root), ["999", "1234", "1254"]);
    deepStrictEqual(cachedRevisions(join(s.dir, "absent")), []);
  } finally {
    s.done();
  }
});

test("the check passes for the pinned build, and names it", () => {
  const s = scratch();
  try {
    const pw = cache(s.dir, COMPLETE);
    const env = { GRADLE_USER_HOME: gradleHome(s.dir, "1.64.0", BROWSERS()), PLAYWRIGHT_BROWSERS_PATH: pw };
    deepStrictEqual(check(repo(s.dir), env, "darwin", "/nowhere"),
      { code: 0, message: `Playwright 1.64.0's Chromium 1248 is installed in ${pw}` });
  } finally {
    s.done();
  }
});

test("the check fails for other revisions or a cut-short install, naming what the cache holds", () => {
  const s = scratch();
  try {
    const env = (pw) => ({ GRADLE_USER_HOME: gradleHome(join(s.dir, pw), "1.64.0", BROWSERS()),
      PLAYWRIGHT_BROWSERS_PATH: join(s.dir, pw, "ms-playwright") });
    cache(join(s.dir, "other"), ["chromium_headless_shell-1234", "chromium_headless_shell-1254", "ffmpeg-1011"]);
    deepStrictEqual(check(repo(join(s.dir, "other")), env("other"), "darwin", "/nowhere"), { code: 1,
      message: `Playwright 1.64.0's Chromium 1248 is not installed in ${join(s.dir, "other", "ms-playwright")}`
        + " (it holds 1234, 1254)" });
    cache(join(s.dir, "cut"), COMPLETE, ["chromium_headless_shell-1248"]);
    deepStrictEqual(check(repo(join(s.dir, "cut")), env("cut"), "darwin", "/nowhere"), { code: 1,
      message: `Playwright 1.64.0's Chromium 1248 is not installed in ${join(s.dir, "cut", "ms-playwright")}` });
    mkdirSync(join(s.dir, "empty"));
    deepStrictEqual(check(repo(join(s.dir, "empty")), env("empty"), "darwin", "/nowhere"), { code: 1,
      message: `Playwright 1.64.0's Chromium 1248 is not installed in ${join(s.dir, "empty", "ms-playwright")}` });
  } finally {
    s.done();
  }
});

test("the check cannot tell without the lockfile, its driver line, the jar or a pinned chromium", () => {
  const s = scratch();
  try {
    const at = (name) => { mkdirSync(join(s.dir, name)); return join(s.dir, name); };
    const pw = cache(s.dir, COMPLETE);
    const home = gradleHome(at("jar"), "1.64.0", BROWSERS());
    const noLock = repo(at("nolock"), null);
    deepStrictEqual(check(noLock, { GRADLE_USER_HOME: home }, "darwin", "/nowhere"),
      { code: 2, message: `no gradle.lockfile in ${noLock}` });
    deepStrictEqual(check(repo(at("nodriver"), "org.example:x:1=runtimeClasspath"), { GRADLE_USER_HOME: home },
      "darwin", "/nowhere"), { code: 2, message: "gradle.lockfile names no Playwright driver" });
    deepStrictEqual(check(repo(at("newer"), LOCK.replaceAll("1.64.0", "1.65.0")), { GRADLE_USER_HOME: home },
      "darwin", "/nowhere"), { code: 2, message: "Playwright 1.65.0's driver jar is not in the Gradle cache" });
    const noShell = gradleHome(at("noshell"), "1.64.0", BROWSERS({ "chromium-headless-shell": { revision: undefined } }));
    deepStrictEqual(check(repo(join(s.dir, "noshell")), { GRADLE_USER_HOME: noShell, PLAYWRIGHT_BROWSERS_PATH: pw },
      "darwin", "/nowhere"),
    { code: 2, message: "Playwright 1.64.0's browsers.json pins no chromium-headless-shell" });
    deepStrictEqual(check(repo(at("inside")), { GRADLE_USER_HOME: home, PLAYWRIGHT_BROWSERS_PATH: "0" },
      "darwin", "/nowhere"),
    { code: 2, message: "PLAYWRIGHT_BROWSERS_PATH=0 keeps the browsers inside the driver package" });
  } finally {
    s.done();
  }
});

// The gate itself, in ./jclaw.sh test, with both halves of the run skipped so only its line is in question.
function gate(env) {
  const base = { ...process.env, JCLAW_TEST_BACKEND: "none", JCLAW_TEST_FRONTEND: "0" };
  delete base.JCLAW_PLAYWRIGHT_TEST;
  const run = spawnSync(join(ROOT, "jclaw.sh"), ["test"], { cwd: ROOT, env: { ...base, ...env }, encoding: "utf8" });
  strictEqual(run.status, 0, run.stdout + run.stderr);
  return run.stdout.split("\n")[0];
}

const VERSION = lockedDriverVersion(readFileSync(join(ROOT, "gradle.lockfile"), "utf8"));

test("./jclaw.sh test leaves the live-browser tests off for a cache of other revisions, and says what installs the pinned one", () => {
  const s = scratch();
  try {
    const pw = cache(s.dir, ["chromium-1254", "chromium_headless_shell-1234", "chromium_headless_shell-1254"]);
    const home = gradleHome(s.dir, VERSION, BROWSERS());
    strictEqual(gate({ GRADLE_USER_HOME: home, PLAYWRIGHT_BROWSERS_PATH: pw }),
      `==> Playwright ${VERSION}'s Chromium 1248 is not installed in ${pw} (it holds 1234, 1254): `
        + "the live-browser tests stay skipped. ./gradlew playwrightInstall installs it.");
  } finally {
    s.done();
  }
});

test("./jclaw.sh test turns the live-browser tests on for the pinned build", () => {
  const s = scratch();
  try {
    const pw = cache(s.dir, COMPLETE);
    strictEqual(gate({ GRADLE_USER_HOME: gradleHome(s.dir, VERSION, BROWSERS()), PLAYWRIGHT_BROWSERS_PATH: pw }),
      `==> Playwright ${VERSION}'s Chromium 1248 is installed in ${pw}: running the live-browser tests too.`);
  } finally {
    s.done();
  }
});

test("./jclaw.sh test says so when it cannot tell, and leaves an explicit JCLAW_PLAYWRIGHT_TEST alone", () => {
  const s = scratch();
  try {
    strictEqual(gate({ GRADLE_USER_HOME: join(s.dir, "empty-gradle") }),
      `==> Cannot tell whether Playwright's Chromium is installed (Playwright ${VERSION}'s driver jar is not in the `
        + "Gradle cache): the live-browser tests stay skipped.");
    strictEqual(gate({ JCLAW_PLAYWRIGHT_TEST: "0" }), "==> Backend tests skipped: the change reaches none.");
  } finally {
    s.done();
  }
});
