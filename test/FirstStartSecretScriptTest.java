import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import play.Play;
import play.test.UnitTest;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.PosixFilePermissions;
import java.util.List;
import java.util.Map;
import java.util.concurrent.TimeUnit;
import java.util.regex.Pattern;

/**
 * Runs the secret steps of jclaw.sh's start, {@code ensure_env_for_start}, {@code load_env_file} and
 * {@code require_application_secret} with {@code do_secret} as written, against a scratch install whose
 * {@code play} is a stub. The launcher that cannot run is a script whose interpreter does not exist, which
 * fails as the bundle's {@code play} did in a nixos/nix container ({@code bad interpreter}, exit 126).
 */
class FirstStartSecretScriptTest extends UnitTest {

    private static final List<String> FUNCTIONS = List.of("secret_var_name", "env_file_value", "load_env_file",
            "ensure_env_for_start", "uses_external_database", "require_application_secret", "do_secret");

    private static final String START = """
            ensure_env_for_start
            load_env_file
            require_application_secret
            printf 'started with %s\\n' "$PLAY_SECRET"
            """;

    private static final String UNRUNNABLE = """
            #!/nonexistent/bash
            """;

    /** Writes the secret as the bundle launcher's {@code secret} does: appended, or replacing the line that holds one. */
    private static final String LAUNCHER = """
            #!/bin/bash
            echo "play $*" >> "$STUB_CALLS"
            [ "$1" = secret ] || exit 2
            if grep -q '^PLAY_SECRET=' certs/.env 2>/dev/null; then
                sed "s/^PLAY_SECRET=.*/PLAY_SECRET=$STUB_SECRET/" certs/.env > certs/.env.tmp && mv certs/.env.tmp certs/.env
            else
                printf 'PLAY_SECRET=%s\\n' "$STUB_SECRET" >> certs/.env
            fi
            echo "~ PLAY_SECRET written to certs/.env"
            """;

    /** What {@code do_secret} seeds a new certs/.env with, and all v1.0.26's failed first start left there. */
    private static final String HEADER = """
            # Per-clone environment overrides sourced by jclaw.sh.
            # Generated by 'jclaw.sh secret' or 'jclaw.sh setup' — do not commit.

            # Admin password used by 'jclaw.sh e2e' to sign in before the Playwright
            # specs run. Belongs here rather than conf/application.conf, which is
            # tracked and ships to both remotes. Uncomment and set to use it.
            #JCLAW_ADMIN_PASSWORD=
            """;

    private static final String GENERATED = """
            ~ PLAY_SECRET written to certs/.env
                Restart the app to pick up the new value:
                  jclaw.sh restart
            """;

    @TempDir Path tmp;

    private Path install;
    private Path env;
    private Path calls;

    private record Run(int exit, String out) {}

    @BeforeEach
    void scratchInstall() throws Exception {
        install = tmp.resolve("jclaw");
        Files.createDirectories(install.resolve("conf"));
        Files.writeString(install.resolve("conf/application.conf"), "application.secret=${PLAY_SECRET}\n");
        Files.createDirectories(tmp.resolve("bin"));
        env = install.resolve("certs/.env");
        calls = tmp.resolve("calls");
        Files.writeString(calls, "");
    }

    @Test
    void aFirstStartWhoseLauncherCannotRunLeavesTheNextStartToGenerateTheSecret() throws Exception {
        launcher(UNRUNNABLE);
        var failed = run(START, Map.of());
        assertNotEquals(0, failed.exit(), failed.out());

        launcher(LAUNCHER);
        var next = run(START, Map.of("STUB_SECRET", "secret-of-the-second-start"));

        assertEquals(0, next.exit(), next.out());
        assertEquals("==> First run detected — no certs/.env and no PLAY_SECRET in env.\n" + GENERATED
                + "started with secret-of-the-second-start\n", next.out());
        assertEquals(HEADER + "PLAY_SECRET=secret-of-the-second-start\n", Files.readString(env));
        assertEquals("rw-------", PosixFilePermissions.toString(Files.getPosixFilePermissions(env)));
    }

    @Test
    void aFirstStartWhoseLauncherCannotRunLeavesNoCertsEnvBehind() throws Exception {
        launcher(UNRUNNABLE);

        var run = run(START, Map.of());

        assertEquals(1, run.exit(), run.out());
        var lines = run.out().lines().toList();
        assertEquals(3, lines.size(), run.out());
        assertEquals("==> First run detected — no certs/.env and no PLAY_SECRET in env.", lines.get(0));
        // bash's own line, worded by its version: 3.2, 5.1 and 5.3 say "bad interpreter", 5.2 "required file not found".
        assertTrue(Pattern.matches("(jclaw\\.sh|environment)(: line \\d+)?: " + Pattern.quote(tmp.resolve("bin/play").toString())
                + ": (/nonexistent/bash: bad interpreter: No such file or directory|cannot execute: required file not found)",
                lines.get(1)), lines.get(1));
        assertEquals("Error: 'play secret' did not write a new PLAY_SECRET to certs/.env.", lines.get(2));
        assertFalse(Files.exists(env), "the half-made certs/.env is removed");
    }

    @Test
    void aLauncherThatWritesAnEmptySecretFailsTheStartAndLeavesNoCertsEnvBehind() throws Exception {
        launcher(LAUNCHER);

        var run = run(START, Map.of("STUB_SECRET", ""));

        assertEquals(1, run.exit(), run.out());
        assertEquals("==> First run detected — no certs/.env and no PLAY_SECRET in env.\n"
                + "~ PLAY_SECRET written to certs/.env\n"
                + "Error: 'play secret' did not write a new PLAY_SECRET to certs/.env.\n", run.out());
        assertFalse(Files.exists(env));
    }

    @Test
    void aCertsEnvLeftWithoutASecretBeforeTheDatabaseExistsGetsOneAtTheNextStart() throws Exception {
        envFile(HEADER);
        launcher(LAUNCHER);

        var run = run(START, Map.of("STUB_SECRET", "healed"));

        assertEquals(0, run.exit(), run.out());
        assertEquals("==> First run detected — certs/.env holds no PLAY_SECRET and there is no database yet.\n"
                + GENERATED + "started with healed\n", run.out());
        assertEquals(HEADER + "PLAY_SECRET=healed\n", Files.readString(env));
    }

    @Test
    void aCertsEnvWithAnEmptySecretBeforeTheDatabaseExistsGetsOneAtTheNextStart() throws Exception {
        envFile(HEADER + "PLAY_SECRET=\n");
        launcher(LAUNCHER);

        var run = run(START, Map.of("STUB_SECRET", "healed"));

        assertEquals(0, run.exit(), run.out());
        assertEquals("==> First run detected — certs/.env holds no PLAY_SECRET and there is no database yet.\n"
                + GENERATED + "started with healed\n", run.out());
        assertEquals(HEADER + "PLAY_SECRET=healed\n", Files.readString(env));
    }

    @Test
    void aCertsEnvWithoutASecretBesideADatabaseStopsTheStartAndGeneratesNone() throws Exception {
        envFile(HEADER);
        Files.createDirectories(install.resolve("data"));
        Files.writeString(install.resolve("data/jclaw.mv.db"), "");
        launcher(LAUNCHER);

        var run = run(START, Map.of("STUB_SECRET", "must-not-appear"));

        assertEquals(1, run.exit(), run.out());
        assertEquals("""
                Error: PLAY_SECRET resolved to empty after sourcing certs/.env.
                       Check that certs/.env contains a non-empty value:
                         PLAY_SECRET=<some-64-char-string>
                       Rotate or regenerate with: jclaw.sh secret
                """, run.out());
        assertEquals("", Files.readString(calls));
        assertEquals(HEADER, Files.readString(env));
    }

    @Test
    void aCertsEnvWithoutASecretOnAnExternalDatabaseStopsTheStartAndGeneratesNone() throws Exception {
        Files.writeString(install.resolve("conf/application.conf"),
                "application.secret=${PLAY_SECRET}\n%prod.db.url=jdbc:postgresql://localhost:5432/jclaw\n");
        envFile(HEADER);
        launcher(LAUNCHER);

        var run = run(START, Map.of("STUB_SECRET", "must-not-appear"));

        assertEquals(1, run.exit(), run.out());
        assertEquals("""
                Error: PLAY_SECRET resolved to empty after sourcing certs/.env.
                       Check that certs/.env contains a non-empty value:
                         PLAY_SECRET=<some-64-char-string>
                       Rotate or regenerate with: jclaw.sh secret
                """, run.out());
        assertEquals("", Files.readString(calls));
        assertEquals(HEADER, Files.readString(env));
    }

    @Test
    void theH2UrlBesideTheCommentedPostgresTemplateStillLetsTheNextStartWriteTheSecret() throws Exception {
        Files.writeString(install.resolve("conf/application.conf"), """
                application.secret=${PLAY_SECRET}
                db.url=jdbc:h2:retry:./data/jclaw;MODE=MYSQL;AUTO_SERVER=TRUE
                # %prod.db.url=jdbc:postgresql://localhost:5432/jclaw
                """);
        envFile(HEADER);
        launcher(LAUNCHER);

        var run = run(START, Map.of("STUB_SECRET", "healed"));

        assertEquals(0, run.exit(), run.out());
        assertEquals("==> First run detected — certs/.env holds no PLAY_SECRET and there is no database yet.\n"
                + GENERATED + "started with healed\n", run.out());
        assertEquals(HEADER + "PLAY_SECRET=healed\n", Files.readString(env));
    }

    @Test
    void aSecretAlreadyInCertsEnvStartsWithoutRunningTheLauncher() throws Exception {
        envFile(HEADER + "PLAY_SECRET=kept\n");
        launcher(UNRUNNABLE);

        var run = run(START, Map.of());

        assertEquals(0, run.exit(), run.out());
        assertEquals("started with kept\n", run.out());
        assertEquals(HEADER + "PLAY_SECRET=kept\n", Files.readString(env));
    }

    @Test
    void aSecretTheParentShellExportsIsUsedAndNoCertsEnvIsWritten() throws Exception {
        launcher(UNRUNNABLE);

        var run = run(START, Map.of("PLAY_SECRET", "from-the-shell"));

        assertEquals(0, run.exit(), run.out());
        assertEquals("started with from-the-shell\n", run.out());
        assertFalse(Files.exists(env));
    }

    @Test
    void aRotationWhoseLauncherCannotRunKeepsTheSecretCertsEnvHeld() throws Exception {
        envFile(HEADER + "PLAY_SECRET=outgoing\n");
        launcher(UNRUNNABLE);

        var run = run("do_secret\n", Map.of());

        assertEquals(1, run.exit(), run.out());
        assertEquals("Error: 'play secret' did not write a new PLAY_SECRET to certs/.env.",
                run.out().lines().toList().getLast());
        assertEquals(HEADER + "PLAY_SECRET=outgoing\n"
                + "# PLAY_SECRET_PREVIOUS: the secret before the last rotation. Remove it once JClaw logs that it can go.\n"
                + "PLAY_SECRET_PREVIOUS=outgoing\n", Files.readString(env));
    }

    private void launcher(String body) throws Exception {
        var play = tmp.resolve("bin/play");
        Files.writeString(play, body);
        Files.setPosixFilePermissions(play, PosixFilePermissions.fromString("rwxr-xr-x"));
    }

    private void envFile(String body) throws Exception {
        Files.createDirectories(env.getParent());
        Files.writeString(env, body);
        Files.setPosixFilePermissions(env, PosixFilePermissions.fromString("rw-------"));
    }

    private Run run(String steps, Map<String, String> extraEnv) throws Exception {
        var script = Files.readString(Path.of(Play.applicationPath.getAbsolutePath()).resolve("jclaw.sh"));
        var harness = new StringBuilder("set -euo pipefail\nSCRIPT_DIR='" + install + "'\nDEV_MODE=false\n");
        for (var name : FUNCTIONS) {
            var m = Pattern.compile("(?ms)^" + Pattern.quote(name) + "\\(\\) \\{\\n.*?^\\}\\n").matcher(script);
            assertTrue(m.find(), "jclaw.sh no longer defines " + name);
            harness.append(m.group());
        }
        harness.append(steps);
        // $0 is what the messages name as the command; the script's own name keeps the assertions exact.
        var pb = new ProcessBuilder("/bin/bash", "-c", harness.toString(), "jclaw.sh").redirectErrorStream(true);
        // The autotest server runs with a generated PLAY_SECRET, which would stand in for the one under test.
        pb.environment().remove("PLAY_SECRET");
        pb.environment().remove("PLAY_SECRET_PREVIOUS");
        pb.environment().put("PATH", tmp.resolve("bin") + ":" + System.getenv("PATH"));
        pb.environment().put("STUB_CALLS", calls.toString());
        pb.environment().putAll(extraEnv);
        var p = pb.start();
        var out = new String(p.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
        assertTrue(p.waitFor(30, TimeUnit.SECONDS), "the harness hung");
        return new Run(p.exitValue(), out);
    }
}
